import { existsSync, readFileSync, writeFileSync } from "node:fs";

const sources = [
  "assets_src/chapter1/scenes/apartment/layers.json",
  "assets_src/chapter1/scenes/village_square/layers.json"
];
const outputPath = "src/content/chapter1/sceneLayers.generated.js";

const sceneLayerGeometry = {};

for (const sourcePath of sources) {
  if (!existsSync(sourcePath)) continue;
  const source = JSON.parse(readFileSync(sourcePath, "utf8"));
  if (!source.sceneId) throw new Error(`${sourcePath} sceneId is required`);
  sceneLayerGeometry[source.sceneId] = {
    sceneId: source.sceneId,
    foregroundLayers: (source.layers || [])
      .filter((layer) => layer.enabled !== false)
      .map((layer) => runtimeLayer(layer, sourcePath))
  };
}

writeFileSync(
  outputPath,
  `// Generated by tools/build-scene-layer-runtime.js. Edit assets_src scene layer sources instead.\nexport const sceneLayerGeometry = ${JSON.stringify(sceneLayerGeometry, null, 2)};\n`
);

function runtimeLayer(layer, sourcePath) {
  if (!layer.id) throw new Error(`${sourcePath} layer id is required`);
  if (!layer.asset) throw new Error(`${sourcePath} ${layer.id} asset is required`);
  if (!Number.isFinite(Number(layer.zIndex))) throw new Error(`${sourcePath} ${layer.id} zIndex must be a number`);
  const result = {
    id: layer.id,
    asset: layer.asset,
    zIndex: Number(layer.zIndex)
  };
  copyNumber(layer, result, "top");
  copyNumber(layer, result, "left");
  copyNumber(layer, result, "right");
  copyNumber(layer, result, "bottom");
  if (layer.visibleWhenFlag) result.visibleWhenFlag = String(layer.visibleWhenFlag);
  if (layer.hiddenWhenItemOwned) result.hiddenWhenItemOwned = String(layer.hiddenWhenItemOwned);
  if (layer.visibleDuringAction) {
    result.visibleDuringAction = {
      actionName: String(layer.visibleDuringAction.actionName || ""),
      fromFrame: Math.max(0, Math.floor(Number(layer.visibleDuringAction.fromFrame) || 0))
    };
  }
  if (!hasNumber(result, "top") && !hasNumber(result, "bottom")) result.top = 0;
  if (!hasNumber(result, "left") && !hasNumber(result, "right")) result.left = 0;
  return result;
}

function copyNumber(from, to, key) {
  if (Number.isFinite(Number(from[key]))) to[key] = Number(from[key]);
}

function hasNumber(value, key) {
  return Number.isFinite(Number(value[key]));
}
