import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname } from "node:path";

const SOURCES = [
  {
    name: "apartmentObjectGeometry",
    path: "assets_src/chapter1/scenes/apartment/object-geometry-v1.json"
  }
];

const OUTPUT = "src/content/chapter1/sceneObjectGeometry.generated.js";

function readJson(path) {
  return JSON.parse(readFileSync(path, "utf8"));
}

function normalizePoint(point, sourceId, objectId, index) {
  const x = Number(point?.x);
  const y = Number(point?.y);
  if (!Number.isFinite(x) || !Number.isFinite(y)) {
    throw new Error(`${sourceId} ${objectId} polygon[${index}] must have finite x/y`);
  }
  return { x: Math.round(x), y: Math.round(y) };
}

function buildGeometry(source) {
  const objects = {};
  for (const object of source.objects || []) {
    if (!object.id) throw new Error(`${source.id} object is missing id`);
    const polygon = object.polygon || rectToPolygon(object.rect);
    if (!Array.isArray(polygon) || polygon.length < 3) {
      throw new Error(`${source.id} ${object.id} needs polygon with at least 3 points`);
    }
    objects[object.id] = {
      id: object.id,
      polygon: polygon.map((point, index) => normalizePoint(point, source.id, object.id, index))
    };
  }
  return {
    id: source.id,
    sceneId: source.sceneId,
    sourceBackground: source.sourceBackground,
    world: source.world,
    objects
  };
}

function rectToPolygon(rect) {
  if (!rect) return null;
  const x = Number(rect.x);
  const y = Number(rect.y);
  const w = Number(rect.w);
  const h = Number(rect.h);
  if (![x, y, w, h].every(Number.isFinite)) return null;
  return [
    { x, y },
    { x: x + w, y },
    { x: x + w, y: y + h },
    { x, y: y + h }
  ];
}

const generated = {};
for (const entry of SOURCES) {
  generated[entry.name] = buildGeometry(readJson(entry.path));
}

mkdirSync(dirname(OUTPUT), { recursive: true });
writeFileSync(
  OUTPUT,
  `// Generated by tools/build-scene-object-geometry.js. Edit assets_src chapter object geometry sources instead.\n${Object.entries(generated)
    .map(([name, value]) => `export const ${name} = ${JSON.stringify(value, null, 2)};`)
    .join("\n\n")}\n`
);

